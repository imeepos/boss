#!/usr/bin/env node
// 生成 bossctl 路由目录: api/openapi/{admin,user,worker}/*.yaml -> cmd/bossctl/routes_<portal>.go
// 目录漂移由此收敛:openapi 为单一事实源,勿手改生成文件。
// 用法: node scripts/gen-bossctl-routes.mjs   (在仓库根执行)
import fs from 'node:fs';
import path from 'node:path';
const NL = String.fromCharCode(10);
const METHODS = ['get', 'post', 'put', 'delete', 'patch'];
const PORTALS = [
  { name: 'admin', prefix: '/api/admin/v1', out: 'cmd/bossctl/routes_admin.go', var: 'adminRoutes' },
  { name: 'user', prefix: '/api/user/v1', out: 'cmd/bossctl/routes_user.go', var: 'userRoutes' },
  { name: 'worker', prefix: '/api/worker/v1', out: 'cmd/bossctl/routes_worker.go', var: 'workerRoutes' },
];

function parseFile(file) {
  const routes = [];
  let curPath = null, curMethod = null;
  for (const ln of fs.readFileSync(file, 'utf8').split(NL)) {
    if (/^  '?\//.test(ln)) { curPath = ln.trim().replace(/^'|'$/g, '').slice(0, -1); curMethod = null; continue; }
    const t = ln.trim();
    const ind = ln.length - ln.replace(/^ +/, '').length;
    if (curPath && ind === 4 && t.endsWith(':')) {
      const m = t.slice(0, -1);
      if (METHODS.includes(m)) { curMethod = m; routes.push({ method: m.toUpperCase(), path: curPath, desc: '' }); continue; }
    }
    if (curMethod && ind === 6 && t.startsWith('summary:')) {
      routes[routes.length - 1].desc = t.slice(8).trim().replace(/^['"]|['"]$/g, '');
    }
  }
  return routes;
}

for (const p of PORTALS) {
  const dir = path.join('api/openapi', p.name);
  const routes = [];
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.yaml') && x !== 'schemas.yaml').sort()) {
    routes.push(...parseFile(path.join(dir, f)));
  }
  const goParam = s => s.replace(/{([a-zA-Z]+)}/g, ':$1');
  const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const lines = [
    '// Code generated by scripts/gen-bossctl-routes.mjs from api/openapi; DO NOT EDIT.',
    `// ${p.name} 端路由目录(前缀 ${p.prefix}),再生成: node scripts/gen-bossctl-routes.mjs`,
    '',
    'package main',
    '',
    `var ${p.var} = []routeEntry{`,
    ...routes.map(r =>
      `\t{"${r.method}", "${esc(goParam(r.path))}", "${esc(r.desc || '')}"},`),
    '}',
    '',
  ];
  fs.writeFileSync(p.out, lines.join(NL));
  console.log(`${p.out}: ${routes.length} 条路由`);
}
