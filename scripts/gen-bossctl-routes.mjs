#!/usr/bin/env node
// 生成路由目录: api/openapi/{admin,user,worker}/*.yaml
//   -> cmd/bossctl/routes_<portal>.go    (bossctl CLI 三端目录,{x} 转 :x Gin 风格)
//   -> internal/apiroutes/routes_gen.go  (bossmcp MCP server 用户端+师傅端目录,保留 {x} 占位)
// 目录漂移由此收敛:openapi 为单一事实源,勿手改生成文件。
// 用法: node scripts/gen-bossctl-routes.mjs          (在仓库根执行,写盘)
//       node scripts/gen-bossctl-routes.mjs --check  (内存比对不写盘,漂移 exit 1;make check 门禁)
import fs from 'node:fs';
import path from 'node:path';
const NL = String.fromCharCode(10);
const CHECK = process.argv.includes('--check');
const METHODS = ['get', 'post', 'put', 'delete', 'patch'];
const PORTALS = [
  { name: 'admin', prefix: '/api/admin/v1', out: 'cmd/bossctl/routes_admin.go', var: 'adminRoutes' },
  { name: 'user', prefix: '/api/user/v1', out: 'cmd/bossctl/routes_user.go', var: 'userRoutes' },
  { name: 'worker', prefix: '/api/worker/v1', out: 'cmd/bossctl/routes_worker.go', var: 'workerRoutes' },
];

function parseFile(file) {
  const routes = [];
  let curPath = null, curMethod = null;
  for (const ln of fs.readFileSync(file, 'utf8').split(NL)) {
    if (/^  '?\//.test(ln)) {
      // 路径键:先去尾部冒号再剥包裹引号(带引号键剥引号在前会残留尾引号)
      let p = ln.trim();
      if (p.endsWith(':')) p = p.slice(0, -1);
      curPath = p.replace(/^'|'$/g, ''); curMethod = null; continue;
    }
    const t = ln.trim();
    const ind = ln.length - ln.replace(/^ +/, '').length;
    if (curPath && ind === 4 && t.endsWith(':')) {
      const m = t.slice(0, -1);
      if (METHODS.includes(m)) { curMethod = m; routes.push({ method: m.toUpperCase(), path: curPath, desc: '' }); continue; }
    }
    if (curMethod && ind === 6 && t.startsWith('summary:')) {
      routes[routes.length - 1].desc = t.slice(8).trim().replace(/^['"]|['"]$/g, '');
    }
  }
  return routes;
}

// collectRoutes 汇总单端 openapi 目录并去重(同一路由多 yaml 重复登记只保留首次)。
function collectRoutes(portal) {
  const dir = path.join('api/openapi', portal.name);
  const collected = [];
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.yaml') && x !== 'schemas.yaml').sort()) {
    collected.push(...parseFile(path.join(dir, f)));
  }
  const seen = new Set();
  return collected.filter(r => {
    const k = r.method + ' ' + r.path;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

// emit 生成单文件内容;CHECK 模式只比对不写盘,漂移即失败(契约变更后忘了再生成在此拦截)。
function emit(out, lines, label) {
  const content = lines.join(NL);
  if (CHECK) {
    const onDisk = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (onDisk !== content) {
      console.error(`DRIFT ${out}: 与 api/openapi 不一致,执行 node scripts/gen-bossctl-routes.mjs 后随契约变更同提交`);
      process.exitCode = 1;
    } else {
      console.log(`CHECK OK ${out}: ${label}`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, content);
  console.log(`${out}: ${label}`);
}

for (const p of PORTALS) {
  const routes = collectRoutes(p);
  const goParam = s => s.replace(/{([a-zA-Z]+)}/g, ':$1');
  emit(p.out, [
    '// Code generated by scripts/gen-bossctl-routes.mjs from api/openapi; DO NOT EDIT.',
    `// ${p.name} 端路由目录(前缀 ${p.prefix}),再生成: node scripts/gen-bossctl-routes.mjs`,
    '',
    'package main',
    '',
    `var ${p.var} = []routeEntry{`,
    ...routes.map(r =>
      `\t{"${r.method}", "${esc(goParam(r.path))}", "${esc(r.desc || '')}"},`),
    '}',
    '',
  ], `${routes.length} 条路由`);
}

// MCP 目录(cmd/bossmcp 用):三端,{param} 占位保留原样供 LLM 阅读与拼路径;
// admin 目录在 bossmcp 内按当前账号权限二次过滤(数据源 internal/apiroutes/admin_perms_gen.go)。
const mcpPortals = PORTALS.map(p => ({ ...p, routes: collectRoutes(p) }));
emit('internal/apiroutes/routes_gen.go', [
  '// Code generated by scripts/gen-bossctl-routes.mjs from api/openapi; DO NOT EDIT.',
  '// 三端 MCP 路由目录(前缀见 Portals;admin 端 boss_routes 按账号权限过滤后再暴露),再生成: node scripts/gen-bossctl-routes.mjs',
  '',
  'package apiroutes',
  '',
  '// Route 单条 API 路由目录项(Path 保留 {param} 占位风格)。',
  'type Route struct {',
  '\tMethod string',
  '\tPath   string',
  '\tDesc   string',
  '}',
  '',
  '// Portal 单端路由目录。',
  'type Portal struct {',
  '\tName   string // user / worker / admin',
  '\tPrefix string // API 前缀,如 /api/user/v1',
  '\tRoutes []Route',
  '}',
  '',
  '// Portals 三端路由目录。',
  'var Portals = []Portal{',
  ...mcpPortals.flatMap(p => [
    `\t{Name: "${p.name}", Prefix: "${p.prefix}", Routes: []Route{`,
    ...p.routes.map(r => `\t\t{"${r.method}", "${esc(r.path)}", "${esc(r.desc || '')}"},`),
    '\t}},',
  ]),
  '}',
  '',
], `${mcpPortals.map(p => `${p.name} ${p.routes.length} 条`).join(' + ')} 路由`);
