CREATE TABLE odn_region_code (
    prv_code  CHAR(6)     PRIMARY KEY CHECK (prv_code ~ '^[A-Z]{3}[0-9]{3}$'),
    psgc_code VARCHAR(16) NOT NULL REFERENCES geo_subdivision(code),
    spec_name VARCHAR(64) NOT NULL,
    note      VARCHAR(255)
);
CREATE INDEX idx_odn_region_psgc ON odn_region_code(psgc_code);

CREATE TABLE odn_city_code (
    prv_code    CHAR(6)     NOT NULL REFERENCES odn_region_code(prv_code),
    city_prefix VARCHAR(5) NOT NULL CHECK (city_prefix ~ '^[A-Z]{3,5}$'), -- 规范正文称 3 字母,索引表含 CALM/VALC/TANDA 等 4-5 字母,按事实放宽
    psgc_code   VARCHAR(16) NOT NULL REFERENCES geo_subdivision(code),
    spec_name   VARCHAR(64) NOT NULL,
    note        VARCHAR(255),
    PRIMARY KEY (prv_code, city_prefix)
);
CREATE INDEX idx_odn_city_psgc ON odn_city_code(psgc_code);

